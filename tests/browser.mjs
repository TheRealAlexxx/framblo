import assert from 'node:assert/strict';
import http from 'node:http';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
const requireQA = createRequire(path.resolve('.qa/package.json'));
const { chromium } = requireQA('playwright');
const html = await fs.readFile('dist/index.html');
await fs.mkdir('test-results', { recursive: true });
const server = http.createServer((req, res) => {
  if (req.url.startsWith('/api/github/session')) { res.writeHead(200, {'content-type':'application/json'}); return res.end(JSON.stringify({configured:false,connected:false})); }
  res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }); res.end(html);
});
await new Promise(resolve => server.listen(4173, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true });
const checks = [];
const check = name => { checks.push(name); console.log('PASS: ' + name); };
const pageErrors = [];
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page = await context.newPage();
  page.on('pageerror',error=>pageErrors.push(error.message));
  await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>Boolean(window.OC?.getProject && window.FrambloUI));
  await page.locator('.f-empty').waitFor();
  assert.equal(await page.locator('.f-home').isVisible(),true);
  check('Homepage and real template preview initialise');
  assert.equal(await page.locator('#f-featured-frame').getAttribute('sandbox'),'');
  assert.ok((await page.locator('#f-featured-frame').getAttribute('srcdoc')).includes('<html'));
  check('Website preview is sandboxed and uses rendered website HTML');
  await page.screenshot({path:'test-results/home-desktop.png',fullPage:true});
  const initial = await page.evaluate(()=>OC.getProject());
  await page.locator('[data-demo=product]').click();
  assert.equal(await page.locator('#f-demo-name').textContent(),'Product');
  assert.equal(await page.locator('#f-demo-use').getAttribute('data-dash-new'),'product');
  await page.locator('[data-demo=portfolio]').click();
  assert.equal(await page.locator('#f-demo-name').textContent(),'Portfolio');
  assert.equal(await page.evaluate(()=>OC.getProject().id),initial.id);
  check('Template preview switching never changes the current project');
  await page.locator('[data-demo=studio]').click();
  for(const width of [320,390,768,1440]) {
    await page.setViewportSize({width,height:900});
    await page.waitForTimeout(120);
    const dimensions = await page.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
    assert.ok(dimensions.scroll<=dimensions.client+1,`Horizontal overflow at ${width}px: ${JSON.stringify(dimensions)}`);
    check(`Homepage fits ${width}px without horizontal overflow`);
    if(width===390)await page.screenshot({path:'test-results/home-mobile.png',fullPage:true});
  }
  await page.locator('.f-intro [data-dash-new=blank]').click();
  await page.waitForFunction(()=>!document.body.classList.contains('dashboard-mode'));
  await page.waitForFunction(()=>OC.getState().tab==='blocks');
  check('New project opens the functional editor');
  await page.locator('.topbar [data-action=rename]').click();
  await page.locator('#rename-form input').fill('Design QA');
  await page.locator('#rename-form button[type=submit]').click();
  await page.waitForFunction(()=>OC.getProject().name==='Design QA');
  const before = await page.evaluate(()=>OC.getProject().pages[0].blocks.length);
  await page.locator('[data-add=hero]').click();
  await page.waitForFunction(n=>OC.getProject().pages[0].blocks.length===n+1,before);
  check('Section insertion updates actual project data');
  await page.locator('.topbar [data-action=undo]').click();
  await page.waitForFunction(n=>OC.getProject().pages[0].blocks.length===n,before);
  await page.locator('.topbar [data-action=redo]').click();
  await page.waitForFunction(n=>OC.getProject().pages[0].blocks.length===n+1,before);
  check('Undo and redo preserve editor behaviour');
  await page.locator('[data-device=mobile]').click();
  await page.waitForFunction(()=>OC.getState().device==='mobile');
  await page.screenshot({path:'test-results/editor-mobile-preview.png',fullPage:true});
  await page.locator('[data-device=desktop]').click();
  await page.waitForFunction(()=>OC.getState().device==='desktop');
  check('Canvas device switching works');
  await page.screenshot({path:'test-results/editor-desktop.png',fullPage:true});
  await page.waitForTimeout(700);
  await page.reload({waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.OC?.getProject?.().name==='Design QA');
  check('Project survives a real IndexedDB reload');
  await page.locator('.wordmark[data-action=dashboard]').click();
  await page.locator('.f-project[data-dash-open]').first().waitFor();
  assert.equal(await page.locator('.f-project strong').first().textContent(),'Design QA');
  assert.ok(await page.locator('.f-project-preview iframe').count());
  check('Dashboard shows the saved project with a real website preview');
  await page.screenshot({path:'test-results/workspace-desktop.png',fullPage:true});
  await page.locator('.f-project').first().click();
  await page.waitForFunction(()=>!document.body.classList.contains('dashboard-mode'));
  check('Saved project reopens from its card');
  await page.waitForFunction(()=>document.querySelector('#save-status')?.textContent.includes('Saved on this device'));
  const tabB = await context.newPage();
  await tabB.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
  await tabB.waitForFunction(()=>Boolean(window.OC?.getProject));
  await tabB.evaluate(()=>{location.hash='#/editor'});
  await tabB.locator('[data-add=hero]').click();
  await tabB.waitForFunction(()=>document.querySelector('#save-status')?.textContent.includes('Saved on this device'));
  const savedByB = await tabB.evaluate(async()=>(await OC.storage.get(OC.getProject().id)).pages[0].blocks.length);
  await page.locator('[data-add=hero]').click();
  await page.waitForFunction(()=>document.querySelector('#save-status')?.textContent.includes('Changed in another tab'));
  const afterStale = await tabB.evaluate(async()=>(await OC.storage.get(OC.getProject().id)).pages[0].blocks.length);
  assert.equal(afterStale,savedByB);
  check('A stale second tab cannot overwrite work saved by another tab');
  await tabB.close();
  await page.locator('.topbar [data-action=export]').click();
  await page.locator('#modal[open]').waitFor();
  const downloadPromise=page.waitForEvent('download');
  await page.locator('[data-action=download-zip]').click();
  const download=await downloadPromise;
  await download.saveAs('test-results/export.zip');
  const zip=await fs.readFile('test-results/export.zip');
  assert.equal(zip.subarray(0,2).toString(),'PK');
  check('Website ZIP still exports');
  await page.keyboard.press('Escape');
  await page.locator('.topbar [data-action=publish]').click();
  await page.locator('#modal[open]').waitFor();
  assert.equal(await page.locator('#modal input[type=password]').count(),0);
  assert.equal(await page.locator('#modal input[name=token]').count(),0);
  check('Publishing remains the GitHub-connect flow, not a PAT form');
  await page.keyboard.press('Escape');
  await page.locator('.topbar [data-action=export]').click();
  await page.locator('#modal[open]').waitFor();
  await page.locator('[data-action=share-tab]').click();
  await page.locator('[data-action=create-share-link]').click();
  await page.locator('#share-url').waitFor();
  const shareUrl=await page.locator('#share-url').inputValue();
  assert.ok(shareUrl.includes('/#/view/'),shareUrl.slice(0,80));
  check('Preview link is created from the export dialog');
  const shared=await context.newPage();
  await shared.goto(shareUrl,{waitUntil:'networkidle'});
  await shared.locator('#viewer:not([hidden])').waitFor();
  assert.equal(await shared.locator('#viewer-title').textContent(),'Design QA');
  const frameHTML=await shared.locator('#viewer-frame').getAttribute('srcdoc');
  assert.ok(frameHTML&&frameHTML.includes('<html'));
  check('Preview link renders the shared website with no account');
  await shared.screenshot({path:'test-results/share-preview.png'});
  await shared.locator('#viewer-copy').click();
  await shared.waitForFunction(()=>location.hash==='#/editor'&&!document.body.classList.contains('viewer-mode'));
  await shared.waitForFunction(()=>OC.getProject().name==='Design QA');
  await shared.waitForFunction(()=>OC.getProject().pages[0].blocks.length>0);
  check('A viewer can make their own editable copy');
  await shared.close();
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>!document.querySelector('#modal').open);
  await page.setViewportSize({width:390,height:844});
  await page.locator('.rail [data-tab=layers]').click();
  assert.equal(await page.locator('.library.open').isVisible(),true);
  await page.locator('[data-action=close-library]').click();
  await page.locator('.canvas-toolbar [data-action=inspector]').click();
  assert.equal(await page.locator('#inspector.open').isVisible(),true);
  await page.keyboard.press('Escape');
  check('Editor panels open and close on a phone-sized viewport');
  await page.screenshot({path:'test-results/editor-phone.png',fullPage:true});
  assert.deepEqual(pageErrors,[]);
  check('No uncaught JavaScript errors during the complete UI flow');
  await fs.writeFile('test-results/summary.json',JSON.stringify({passed:checks.length,checks,pageErrors},null,2));
  console.log(`FRAMBLO_UI_CHECKS_PASSED=${checks.length}`);
} finally {
  await browser.close();
  await new Promise(resolve=>server.close(resolve));
}
